create table if not exists public.holoprints (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  user_id uuid not null references auth.users(id) on delete cascade,
  title text not null check (char_length(title) between 2 and 100),
  author text not null check (char_length(author) between 2 and 50),
  minecraft_version text not null,
  category text not null,
  description text default '',
  image_url text,
  file_url text not null,
  file_name text not null,
  downloads bigint not null default 0
);

alter table public.holoprints enable row level security;

drop policy if exists "Holoprints visiveis para todos" on public.holoprints;
create policy "Holoprints visiveis para todos" on public.holoprints for select using (true);
drop policy if exists "Usuario publica proprio holoprint" on public.holoprints;
create policy "Usuario publica proprio holoprint" on public.holoprints for insert to authenticated with check (auth.uid() = user_id);
drop policy if exists "Usuario apaga proprio holoprint" on public.holoprints;
create policy "Usuario apaga proprio holoprint" on public.holoprints for delete to authenticated using (auth.uid() = user_id);

insert into storage.buckets (id, name, public, file_size_limit)
values ('holoprints', 'holoprints', true, 52428800)
on conflict (id) do update set public = true, file_size_limit = 52428800;

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('previews', 'previews', true, 5242880, array['image/jpeg','image/png','image/webp','image/gif'])
on conflict (id) do update set public = true, file_size_limit = 5242880;

drop policy if exists "Upload holoprints autenticado" on storage.objects;
create policy "Upload holoprints autenticado" on storage.objects for insert to authenticated
with check (bucket_id = 'holoprints' and (storage.foldername(name))[1] = auth.uid()::text);
drop policy if exists "Upload previews autenticado" on storage.objects;
create policy "Upload previews autenticado" on storage.objects for insert to authenticated
with check (bucket_id = 'previews' and (storage.foldername(name))[1] = auth.uid()::text);
drop policy if exists "Leitura publica holoprints" on storage.objects;
create policy "Leitura publica holoprints" on storage.objects for select using (bucket_id = 'holoprints');
drop policy if exists "Leitura publica previews" on storage.objects;
create policy "Leitura publica previews" on storage.objects for select using (bucket_id = 'previews');
